"""Motion videos — animated text over the brand's photos, rendered with
Remotion (the project in ``dispatch/motion``). Different from the AI-filmed
videos (app/video/video.py, app/video/story.py): nothing is "filmed"; the words are typeset
with a real Khmer font and animated, so Khmer is always spelled right and a
video costs one small AI text call, not seconds of video generation.

    POST /ai/motion          brief → job (background): AI script → render → Library
    GET  /ai/motion/status   can this server render? (needs Node + dispatch/motion)
    GET  /ai/video/{id}      the page polls the job like any other generation

Rendering needs Node and the motion project's node_modules next to the backend
— true on a dev machine; the production image doesn't have them yet, so there
the status says so instead of failing half-way.

THE PACKAGE (split from the one motion.py, 2026-11-04 — the code itself unchanged):
  common.py        routers, folders, icons, music, small text helpers
  templates/       one module per template: its prompt, its scene types, its own helpers
  screens.py       the brand's screenshots, the vision lookups
  styles.py        the template registry (STYLES, goals, wide / tall, the director's guide)
  own_script.py    a pasted script: faithful story, own voice lines, no new numbers
  scenes.py        cleaning each scene the AI writes; the Khmer editor's fields
  story.py         write_script, the Khmer editor, the voice-line passes
  summary.py       the storyboard in words (making-of, live board)
  props.py         build_props, pictures, scene lengths
  voiceover.py     the voice-over, timed
  jobs.py          progress, Stop, background pictures
  rendering.py     the Remotion render
  review.py        AI design's self-check, sketches
  director.py      Auto template choice, attached screenshots
  plan.py          storyboard endpoints, estimate, checked_script
  make.py          POST /ai/motion and _make
  reshape.py       the other shape (16:9 ⇄ 9:16)
  deck_pdf.py      Slides' view and PDF
  edit.py          editing a made video, own voice

A NEW TEMPLATE: its prompt and types in templates/<name>.py, then STYLES (styles.py) and the
scene branches (scenes.py _clean_one, props.py build_props / default_seconds, summary.py).
Everything is offered here as before: `from app.motion import X` and `motion.X` still work.
"""

